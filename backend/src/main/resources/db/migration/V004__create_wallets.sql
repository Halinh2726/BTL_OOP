-- R01: điểm là số nguyên, không bao giờ âm. Bảo vệ 2 lớp:
--   (1) Domain: Wallet.debit() ném lỗi khi không đủ điểm (đóng gói)
--   (2) CSDL : ck_wallets_balance — lưới an toàn cuối cùng
