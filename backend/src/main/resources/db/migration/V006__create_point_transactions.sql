-- =====================================================================
-- V006: Giao dịch điểm — ánh xạ phân cấp đa hình PointTransaction (sealed)
--        ├── CashDeposit    (DOI_DIEM)   + cash_details
--        ├── CashWithdrawal (RUT_DIEM)   + cash_details
--        └── ParkingPayment (THANH_TOAN) + parking_payment_details
-- Bảng cha giữ trường chung; bảng chi tiết giữ trường riêng từng loại.
-- R10: giao dịch chỉ được THÊM, không sửa/xóa -> trigger chặn ở cuối file.
-- =====================================================================

CREATE TABLE point_transactions (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type                 VARCHAR(20) NOT NULL,
    points               BIGINT      NOT NULL,
    source_wallet_id     BIGINT,                 -- ví bị trừ  (NULL với DOI_DIEM)
    target_wallet_id     BIGINT,                 -- ví được cộng (NULL với RUT_DIEM)
    source_balance_after BIGINT,                 -- điểm sau của ví nguồn; điểm trước = sau + points
    target_balance_after BIGINT,                 -- điểm sau của ví đích;  điểm trước = sau - points
    idempotency_key      UUID        NOT NULL,   -- chống xử lý trùng khi bấm xác nhận nhiều lần
    request_hash         VARCHAR(64) NOT NULL,   -- SHA-256 nội dung request, để phát hiện "cùng key, khác nội dung"
    performed_by         BIGINT      NOT NULL,   -- truy vết: quản lý (đổi/rút) hoặc bảo vệ (thanh toán)
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uq_point_transactions_idempotency UNIQUE (idempotency_key),
    CONSTRAINT fk_point_transactions_source      FOREIGN KEY (source_wallet_id) REFERENCES wallets (id),
    CONSTRAINT fk_point_transactions_target      FOREIGN KEY (target_wallet_id) REFERENCES wallets (id),
    CONSTRAINT fk_point_transactions_performer   FOREIGN KEY (performed_by)     REFERENCES users (id),
    CONSTRAINT ck_point_transactions_type        CHECK (type IN ('DOI_DIEM', 'THANH_TOAN', 'RUT_DIEM')),
    CONSTRAINT ck_point_transactions_points      CHECK (points > 0),
    CONSTRAINT ck_point_transactions_balances    CHECK (
        (source_balance_after IS NULL OR source_balance_after >= 0) AND
        (target_balance_after IS NULL OR target_balance_after >= 0)
    ),
    -- "Hình dạng" của từng loại giao dịch: ai là nguồn, ai là đích
    CONSTRAINT ck_point_transactions_shape CHECK (
        (type = 'DOI_DIEM'
            AND source_wallet_id IS NULL     AND target_wallet_id IS NOT NULL
            AND source_balance_after IS NULL AND target_balance_after IS NOT NULL)
     OR (type = 'RUT_DIEM'
            AND source_wallet_id IS NOT NULL AND target_wallet_id IS NULL
            AND source_balance_after IS NOT NULL AND target_balance_after IS NULL)
     OR (type = 'THANH_TOAN'
            AND source_wallet_id IS NOT NULL AND target_wallet_id IS NOT NULL
            AND source_wallet_id <> target_wallet_id
            AND source_balance_after IS NOT NULL AND target_balance_after IS NOT NULL)
    )
);

-- GET /me/transactions: lọc theo ví nguồn HOẶC ví đích, sắp id giảm dần, phân trang theo khóa
CREATE INDEX ix_point_transactions_source ON point_transactions (source_wallet_id, id DESC);
CREATE INDEX ix_point_transactions_target ON point_transactions (target_wallet_id, id DESC);

-- Chi tiết của DOI_DIEM / RUT_DIEM. R11: lưu tỷ lệ quy đổi TẠI THỜI ĐIỂM giao dịch.
CREATE TABLE cash_details (
    transaction_id BIGINT  PRIMARY KEY,
    cash_amount    BIGINT  NOT NULL,             -- tiền mặt (đồng) quản lý nhận vào / trả ra
    cash_per_point INTEGER NOT NULL,

    CONSTRAINT fk_cash_details_transaction FOREIGN KEY (transaction_id) REFERENCES point_transactions (id),
    CONSTRAINT ck_cash_details_amount      CHECK (cash_amount > 0),
    CONSTRAINT ck_cash_details_rate        CHECK (cash_per_point > 0)
);

-- Chi tiết của THANH_TOAN. Một lượt gửi chỉ được thanh toán MỘT lần.
CREATE TABLE parking_payment_details (
    transaction_id BIGINT PRIMARY KEY,
    session_id     BIGINT NOT NULL,

    CONSTRAINT uq_payment_details_session      UNIQUE (session_id),
    CONSTRAINT fk_payment_details_transaction  FOREIGN KEY (transaction_id) REFERENCES point_transactions (id),
    CONSTRAINT fk_payment_details_session      FOREIGN KEY (session_id)     REFERENCES parking_sessions (id)
);

-- ---------------------------------------------------------------------
-- R10: chặn UPDATE / DELETE trên các bảng giao dịch (append-only ledger)
-- ---------------------------------------------------------------------
CREATE FUNCTION fn_reject_ledger_modification() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'R10: bảng % chỉ cho phép thêm mới, không được sửa hay xóa', TG_TABLE_NAME
        USING ERRCODE = 'restrict_violation';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_point_transactions_append_only
    BEFORE UPDATE OR DELETE ON point_transactions
    FOR EACH ROW EXECUTE FUNCTION fn_reject_ledger_modification();

CREATE TRIGGER trg_cash_details_append_only
    BEFORE UPDATE OR DELETE ON cash_details
    FOR EACH ROW EXECUTE FUNCTION fn_reject_ledger_modification();

CREATE TRIGGER trg_parking_payment_details_append_only
    BEFORE UPDATE OR DELETE ON parking_payment_details
    FOR EACH ROW EXECUTE FUNCTION fn_reject_ledger_modification();
